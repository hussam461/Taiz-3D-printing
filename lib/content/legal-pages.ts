export function getLegalPageTemplate(slug: string) {
  return LEGAL_PAGE_TEMPLATES.find((page) => page.slug === slug) ?? null;
}

export function isOriginalSeedLegalBody(slug: string, body: string) {
  return ORIGINAL_SEED_BODIES[slug] === body.trim();
}

export function serializeLegalSections(sections: LegalSection[]) {
  return sections.map((section) => `## ${section.title}\n${section.paragraphs.join("\n\n")}`).join("\n\n");
}

export function parseLegalSections(body: string, fallback?: LegalPageTemplate | null): LegalSection[] {
  const blocks = body.split(/\n\s*\n/).map((block) => block.trim()).filter(Boolean);
  const sections: LegalSection[] = [];
  let current: LegalSection | null = null;
  for (const block of blocks) {
    const lines = block.split(/\r?\n/);
    const heading = lines[0].match(/^##\s+(.+)$/);
    if (heading) {
      if (current) sections.push(current);
      current = { title: heading[1].trim(), paragraphs: lines.slice(1).join("\n").trim() ? [lines.slice(1).join("\n").trim()] : [] };
    } else if (current) {
      current.paragraphs.push(block.replace(/^\s*##\s+/gm, "").trim());
    } else {
      sections.push({ title: "المعلومات", paragraphs: [block] });
    }
  }
  if (current) sections.push(current);
  if (sections.length === 0 && fallback) return fallback.sections;
  return sections;
}
